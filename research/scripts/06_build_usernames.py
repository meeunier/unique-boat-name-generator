"""Build username data from an explicit reviewed selection of catalogue IDs."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
catalogue = json.loads((ROOT / 'research/mariners/catalogue.json').read_text(encoding='utf-8'))
selection = json.loads((ROOT / 'research/mariners/username-selection.json').read_text(encoding='utf-8'))
by_id = {entry['id']: entry for entry in catalogue['entries']}
ids = selection['included']
assert len(ids) == len(set(ids)), 'Duplicate selected character IDs'
assert not set(ids) & set(selection['withheld']), 'A withheld character is selected'
records = []
for key in ids:
    entry = by_id[key]
    assert entry['pool'] == 'mariners' and entry['kind'] in ('fiction', 'legend'), key
    assert re.fullmatch(r'[a-z0-9]+(?:_[a-z0-9]+)*', entry['username_base']), key
    records.append(entry['username_base'])
assert len({r.replace('_', '') for r in records}) == len(records), 'Colliding handles'
lines = [
    '// GENERATED by research/scripts/06_build_usernames.py. Do not edit by hand.',
    f'export const USERNAME_DICTIONARY_VERSION = {json.dumps(selection["dictionary_version"])};',
    'export const USERNAME_BASES: readonly string[] = [',
]
lines.extend('  ' + json.dumps(record, ensure_ascii=False) + ',' for record in records)
lines.append('];')
(ROOT / 'src/data/characters.ts').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Wrote {len(records)} character names to src/data/characters.ts')
